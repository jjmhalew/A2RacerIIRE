"""mkmanifest.py - writes src/datafiles.h: name, size and CRC-32 of every file in the CD's data folder (A2 Racer II,
Dutch 1.01, 03-11-1998), which the first-start copy needs and checks (src/datasetup.c). No game content, only checksums.
python tools/mkmanifest.py extract/data"""
import os, sys, zlib

d = sys.argv[1] if len(sys.argv) > 1 else 'extract/data'
rows = []
for n in sorted(os.listdir(d), key=str.lower):
    p = os.path.join(d, n)
    if os.path.isfile(p):
        b = open(p, 'rb').read()
        rows.append((n, len(b), zlib.crc32(b) & 0xffffffff))
with open('src/datafiles.h', 'w', newline='\n') as o:
    o.write('/* datafiles.h - generated by tools/mkmanifest.py: the files of the data folder of the A2 Racer II CD (Dutch,\n'
            ' * version 1.01 of 03-11-1998) with size and CRC-32, for the first-start copy and --verify (src/datasetup.c).\n'
            ' * required = the engine reads it. */\n')
    o.write('typedef struct { const char *name; unsigned size, crc; int required; } DataFile;\n')
    o.write('static const DataFile DATA_FILES[] = {\n')
    skip = ('.exe', '.dll', '.ico')
    for n, s, c in rows:
        req = 0 if n.lower().endswith(skip) else 1
        o.write(f'    {{ "{n}", {s}u, 0x{c:08x}u, {req} }},\n')
    o.write('};\n#define DATA_FILE_COUNT ((int)(sizeof DATA_FILES / sizeof DATA_FILES[0]))\n')
print(len(rows), 'files')
